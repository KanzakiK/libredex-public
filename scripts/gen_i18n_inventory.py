def main():
    with open(RAW, encoding="utf-8-sig") as f:
        raw = list(csv.DictReader(f))

    missing, rows = [], []
    for r in raw:
        zh = r["zh"]
        if zh not in M:
            missing.append(zh)
            rows.append({**r, "en": "<MISSING>", "note": "manual"})
            continue
        key, en, note = M[zh]
        rows.append({
            "id": r["id"], "key": key, "zh": zh, "en": en,
            "type": r["type"], "count": r["count"],
            "note": note, "locations": r["locations"],
        })

    with open(OUT, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=["id", "key", "zh", "en", "type", "count", "note", "locations"])
        w.writeheader()
        w.writerows(rows)

    print("total:", len(rows), "missing:", len(missing))
    for m in missing:
        print("  MISSING:", m)

if __name__ == "__main__":
    main()
